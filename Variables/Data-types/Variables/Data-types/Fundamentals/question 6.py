##Create a variable name = "Python". Print the first character.

name = "Python"
print(name[0])

##Explanationname = "python": This line creates a variable named name and assigns it the string value "python".name[0]: In Python, strings are ordered sequences (indexed). The indexing starts at 0 for the first character, 1 for the second, and so on. Therefore, name[0] accesses the character at the very beginning of the string, which is 'p'.print(): This function displays the result to the console. In this case, it will print the character 'p'.